import type { CommandShell } from '@shared/domain/compatibility';
import type { CliLaunchPlan } from '../adapters/types';
import { quoteCmd, quoteFish, quotePosix, quotePowerShell } from './quoting';

const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

function assertEnvName(name: string): string {
  if (!ENV_NAME.test(name)) throw new Error(`Invalid environment variable name: ${name}`);
  return name;
}

/**
 * The macOS launcher script. Terminal.app runs `.command` files in a new
 * window but does not inherit Profile Switcher's environment, so the script
 * applies the profile's environment itself. Every interpolated value is a
 * path produced by Profile Switcher or a detected executable, validated and
 * single-quoted; variable names are fixed constants.
 */
export function buildPosixLauncherScript(
  plan: CliLaunchPlan,
  profileId: string,
  pidFile: string | null = null,
): string {
  const lines = [
    '#!/bin/sh',
    `# Generated by Profile Switcher for profile ${profileId}.`,
    '# Written for a single launch; edits will be lost.',
    `cd ${quotePosix(plan.cwd)} || exit 1`,
  ];
  // Record this shell's PID; `exec` below keeps the same PID for the
  // application, which lets Profile Switcher confirm it is running.
  if (pidFile) lines.push(`printf '%s' "$$" > ${quotePosix(pidFile)}`);
  if (plan.env.unset.length > 0) lines.push(`unset ${plan.env.unset.map(assertEnvName).join(' ')}`);
  for (const [name, value] of Object.entries(plan.env.set)) {
    lines.push(`${assertEnvName(name)}=${quotePosix(value)}`, `export ${name}`);
  }
  if (plan.env.prependPath.length > 0) {
    lines.push(`PATH=${plan.env.prependPath.map(quotePosix).join(':')}:"$PATH"`, 'export PATH');
  }
  lines.push(`exec ${[plan.executable, ...plan.args].map(quotePosix).join(' ')}`);
  return `${lines.join('\n')}\n`;
}

/**
 * A command the user can paste into their own terminal. It reproduces the
 * profile's environment changes for that single invocation where the shell
 * allows it (POSIX/fish via `env`), or for the current session (PowerShell,
 * cmd), which the UI states explicitly.
 */
export function buildCopyCommand(
  plan: CliLaunchPlan,
  shell: CommandShell,
  workingDirectorySet: boolean,
): string {
  const set = Object.entries(plan.env.set);
  const unset = plan.env.unset.map(assertEnvName);
  set.forEach(([name]) => assertEnvName(name));

  switch (shell) {
    case 'posix':
    case 'fish': {
      const quote = shell === 'posix' ? quotePosix : quoteFish;
      const parts = ['env'];
      for (const name of unset) parts.push('-u', name);
      for (const [name, value] of set) parts.push(`${name}=${quote(value)}`);
      parts.push(...[plan.executable, ...plan.args].map(quote));
      const command = parts.join(' ');
      return workingDirectorySet ? `cd ${quote(plan.cwd)} && ${command}` : command;
    }
    case 'powershell': {
      const statements: string[] = [];
      if (workingDirectorySet)
        statements.push(`Set-Location -LiteralPath ${quotePowerShell(plan.cwd)}`);
      if (unset.length > 0) {
        statements.push(
          `Remove-Item -ErrorAction SilentlyContinue ${unset.map((name) => `Env:${name}`).join(', ')}`,
        );
      }
      for (const [name, value] of set) statements.push(`$env:${name} = ${quotePowerShell(value)}`);
      statements.push(`& ${[plan.executable, ...plan.args].map(quotePowerShell).join(' ')}`);
      return statements.join('; ');
    }
    case 'cmd': {
      const statements: string[] = [];
      if (workingDirectorySet) statements.push(`cd /d ${quoteCmd(plan.cwd)}`);
      for (const name of unset) statements.push(`set "${name}="`);
      for (const [name, value] of set)
        statements.push(quoteCmd(`${name}=${value}`).replace(/^"/, 'set "'));
      statements.push([plan.executable, ...plan.args].map(quoteCmd).join(' '));
      return statements.join(' & ');
    }
  }
}
