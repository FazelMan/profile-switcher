import { describe, expect, it } from 'vitest';
import {
  buildBrowserOpener,
  chooseBrowser,
  defaultBrowserId,
  detectBrowsers,
  parseMacDefaultBrowser,
  type InstalledBrowser,
} from '../../src/main/browsers';
import { fakeFiles, fakeRunner, fakeSystem } from '../helpers/fake-system';

const chrome: InstalledBrowser = {
  id: 'chrome',
  name: 'Google Chrome',
  family: 'chromium',
  path: '/Applications/Google Chrome.app',
};
const firefox: InstalledBrowser = {
  id: 'firefox',
  name: 'Firefox',
  family: 'firefox',
  path: '/usr/bin/firefox',
};

describe('default browser', () => {
  it('reads the https handler from macOS LaunchServices', async () => {
    const json = JSON.stringify({
      LSHandlers: [
        { LSHandlerContentType: 'public.html', LSHandlerRoleAll: 'com.apple.safari' },
        { LSHandlerURLScheme: 'https', LSHandlerRoleAll: 'com.google.Chrome' },
      ],
    });
    expect(parseMacDefaultBrowser(json)).toBe('com.google.chrome');
    expect(parseMacDefaultBrowser('not json')).toBeNull();
    const runner = fakeRunner(() => ({ exitCode: 0, stdout: json }));
    const system = fakeSystem({ platform: 'darwin', homeDir: '/Users/ana', runner });
    expect(await defaultBrowserId(system)).toBe('chrome');
    expect(runner.calls[0]?.args).toEqual([
      '-convert',
      'json',
      '-o',
      '-',
      '/Users/ana/Library/Preferences/com.apple.LaunchServices/com.apple.launchservices.secure.plist',
    ]);
  });

  it('reports Safari (no separate profiles from the command line) as unsupported', async () => {
    const json = JSON.stringify({
      LSHandlers: [{ LSHandlerURLScheme: 'https', LSHandlerRoleAll: 'com.apple.safari' }],
    });
    const system = fakeSystem({
      platform: 'darwin',
      runner: fakeRunner(() => ({ exitCode: 0, stdout: json })),
    });
    expect(await defaultBrowserId(system)).toBeNull();
  });

  it('asks xdg-settings on Linux', async () => {
    const system = fakeSystem({
      env: { PATH: '/usr/bin' },
      files: fakeFiles({ '/usr/bin/xdg-settings': 'exec' }),
      runner: fakeRunner(() => ({ exitCode: 0, stdout: 'firefox.desktop\n' })),
    });
    expect(await defaultBrowserId(system)).toBe('firefox');
  });
});

describe('detectBrowsers', () => {
  it('finds macOS app bundles and Linux executables', async () => {
    const mac = fakeSystem({
      platform: 'darwin',
      homeDir: '/Users/ana',
      files: fakeFiles({
        '/Applications/Google Chrome.app': 'dir',
        '/Users/ana/Applications/Firefox.app': 'dir',
      }),
    });
    expect((await detectBrowsers(mac)).map((b) => [b.id, b.path])).toEqual([
      ['chrome', '/Applications/Google Chrome.app'],
      ['firefox', '/Users/ana/Applications/Firefox.app'],
    ]);
    const linux = fakeSystem({
      env: { PATH: '/usr/bin' },
      files: fakeFiles({ '/usr/bin/chromium': 'exec' }),
    });
    expect((await detectBrowsers(linux)).map((b) => b.id)).toEqual(['chromium']);
    expect(await detectBrowsers(fakeSystem({ platform: 'win32' }))).toEqual([]);
  });
});

describe('chooseBrowser', () => {
  it('prefers the OS default, falls back to an installed one, and honors off', () => {
    expect(chooseBrowser('auto', [chrome, firefox], 'firefox')).toBe(firefox);
    expect(chooseBrowser('auto', [chrome, firefox], null)).toBe(chrome);
    expect(chooseBrowser('firefox', [chrome, firefox], 'chrome')).toBe(firefox);
    expect(chooseBrowser('edge', [chrome], 'chrome')).toBeNull();
    expect(chooseBrowser('off', [chrome], 'chrome')).toBeNull();
    expect(chooseBrowser('auto', [], null)).toBeNull();
  });
});

describe('buildBrowserOpener', () => {
  it('macOS Chromium: a new instance with the profile folder, URL passed as "$1"', () => {
    const script = buildBrowserOpener(
      chrome,
      '/Users/ana/Library/Application Support/PS/profiles/_browser/work-k3m9tq',
      'darwin',
    );
    expect(script).toBe(
      [
        '#!/bin/sh',
        "# Generated by Profile Switcher: opens a link in this profile's own browser profile.",
        "exec '/usr/bin/open' '-na' '/Applications/Google Chrome.app' '--args' '--user-data-dir=/Users/ana/Library/Application Support/PS/profiles/_browser/work-k3m9tq' '--no-first-run' '--no-default-browser-check' \"$1\"",
        '',
      ].join('\n'),
    );
  });

  it('Linux Firefox: its own profile folder', () => {
    expect(buildBrowserOpener(firefox, '/data/_browser/p', 'linux')).toContain(
      "exec '/usr/bin/firefox' '-profile' '/data/_browser/p' \"$1\"",
    );
  });

  it('refuses relative paths', () => {
    expect(() => buildBrowserOpener(firefox, 'relative/dir', 'linux')).toThrow();
  });
});
